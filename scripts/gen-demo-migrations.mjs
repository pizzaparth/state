// Writes lib/demo/db/migrations.generated.ts: every SQL migration in db/migrations, in
// journal order, split at drizzle's statement breakpoints. The demo database (PGlite in
// the browser) applies these to start from the same schema as production.
// Run after `npm run db:generate`; tests/demo-db.test.ts fails while it is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function demoMigrations() {
  const journal = JSON.parse(readFileSync(join(root, "db/migrations/meta/_journal.json"), "utf8"));
  return journal.entries.map((entry) => ({
    tag: entry.tag,
    statements: readFileSync(join(root, "db/migrations", `${entry.tag}.sql`), "utf8")
      .split("--> statement-breakpoint")
      .map((s) => s.trim())
      .filter(Boolean),
  }));
}

export function renderDemoMigrations() {
  return `// Generated by scripts/gen-demo-migrations.mjs from db/migrations. Do not edit.
export const DEMO_MIGRATIONS: { tag: string; statements: string[] }[] = ${JSON.stringify(demoMigrations(), null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "lib/demo/db/migrations.generated.ts"), renderDemoMigrations());
  console.log("[demo] wrote lib/demo/db/migrations.generated.ts");
}
